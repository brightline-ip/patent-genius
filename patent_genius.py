"""Offline provenance and drafting checks. Python standard library only."""
import argparse, hashlib, json, re, sys
from pathlib import Path
from contracts import manifest_errors, support_errors
def digest(data): return hashlib.sha256(data).hexdigest()
def load(path): return json.loads(Path(path).read_text(encoding="utf-8"))
def safe(base, name):
 p=(base/name).resolve()
 if not p.is_relative_to(base.resolve()): raise ValueError("path escapes manifest directory")
 return p
def validate(manifest, base):
 errors=manifest_errors(manifest); ids=set(); units={}
 if errors: return errors,units
 for d in manifest["documents"]:
  if not re.fullmatch(r"(?:public|authority|client:[A-Za-z0-9_-]+):[A-Za-z0-9_-]+",d["id"]): errors.append("invalid document identifier")
  if d["id"] in ids: errors.append("duplicate document identifier")
  ids.add(d["id"])
  if not d.get("source_locator"): errors.append("missing source locator")
  if d["status"]!="ready": errors.append(d["id"]+": extraction "+d["status"]); continue
  try:
   raw=safe(base,d["text_path"]).read_bytes()
   if digest(raw)!=d["sha256"]: errors.append(d["id"]+": checksum mismatch"); continue
   text=raw.decode("utf-8")
   for u in d["units"]:
    start,end=u["start"],u["end"]
    if not (0<=start<end<=len(text)): errors.append("invalid unit offsets"); continue
    expected=d["id"]+":"+digest((d["sha256"]+":"+str(start)+":"+str(end)).encode())[:24]
    if u["id"]!=expected or u["id"] in units: errors.append("invalid/duplicate evidence ID"); continue
    units[u["id"]]=(d,text[start:end])
  except (OSError,ValueError,UnicodeError) as e: errors.append(d["id"]+": source unavailable: "+str(e))
 for e in manifest.get("events",[]):
  if e["document_id"] not in ids or e.get("responds_to") not in {x["id"] for x in manifest.get("events",[])}|{None}: errors.append("broken prosecution event link")
 return errors,units
def audit(m,base,plan,draft):
 errors,units=validate(m,base); decisions=[]
 errors.extend(support_errors(plan,units))
 if errors: return {"status":"REVIEW_REQUIRED","errors":errors,"decisions":decisions,"draft_sha256":digest(draft.encode()),"manifest_sha256":digest(json.dumps(m,sort_keys=True).encode()),"semantic_support_verified":False,"legal_sufficiency_verified":False}
 for record in plan["support_records"]+plan["issues"]:
  span=record.get("draft_span")
  if span and (len(span)!=2 or any(type(x)is not int for x in span) or not 0<=span[0]<span[1]<=len(draft)): errors.append("invalid support/issue draft span")
 if not plan.get("requirements"): errors.append("empty coverage inventory")
 seen=set()
 for r in plan.get("requirements",[]):
  if r["id"] in seen: errors.append("duplicate requirement")
  seen.add(r["id"])
  if r.get("decision") in ("omitted","unknown"):
   decisions.append(r["id"]+": "+r["decision"]+": "+r.get("reason","")); errors.append(r["id"]+": unresolved coverage"); continue
  if r.get("decision")!="mapped": errors.append("invalid coverage decision"); continue
  a,b=r.get("draft_span",[-1,-1])
  if not 0<=a<b<=len(draft): errors.append(r["id"]+": invalid draft span")
  if not r.get("evidence"): errors.append(r["id"]+": missing evidence")
  for ref in r.get("evidence",[]):
   if ref not in units: errors.append(r["id"]+": missing evidence "+ref)
   elif units[ref][0]["id"].split(":")[:2]!=["client",plan["matter"]]: errors.append(r["id"]+": public or cross-matter source cannot establish client disclosure")
 for q in plan.get("quotations",[]):
  if q["evidence"] not in units or not q.get("text") or q["text"] not in units[q["evidence"]][1] or q["text"] not in draft: errors.append("quotation mismatch")
 for heading in plan.get("required_sections",[]):
  if heading not in draft.splitlines(): errors.append("missing section: "+heading)
 return {"status":"REVIEW_REQUIRED" if errors else "MECHANICAL_CHECKS_ONLY", "errors":errors,"decisions":decisions,"draft_sha256":digest(draft.encode()),"manifest_sha256":digest(json.dumps(m,sort_keys=True).encode()),"semantic_support_verified":False,"legal_sufficiency_verified":False}
def main():
 p=argparse.ArgumentParser(description="Patent Genius offline provenance and drafting checks. Structural checks only; never judges legal sufficiency. DRAFT — generated by Patent Genius; not legal advice; requires review by a registered practitioner."); sub=p.add_subparsers(dest="command",required=True)
 for cmd in ("import","retrieve","audit"):
  a=sub.add_parser(cmd); a.add_argument("manifest")
  if cmd=="import": a.add_argument("--output",required=True)
  if cmd=="retrieve":
   for k in ("namespace","technology","cpc","document-type","application-id"): a.add_argument("--"+k)
  if cmd=="audit": a.add_argument("plan"); a.add_argument("draft")
 args=p.parse_args(); m=load(args.manifest); base=Path(args.manifest).resolve().parent
 errors,units=validate(m,base)
 if args.command=="audit":
  result=audit(m,base,load(args.plan),Path(args.draft).read_text(encoding="utf-8")); result["exported_artifact_sha256"]=digest(Path(args.draft).read_bytes()); print(json.dumps(result,indent=2)); return bool(result["errors"])
 if args.command=="import":
  if errors: print(json.dumps({"status":"BLOCKED","errors":errors})); return 1
  out=Path(args.output); payload=json.dumps(m,indent=2)
  if out.exists() and load(out)!=m: raise ValueError("destination exists with different manifest; choose a new snapshot")
  if not out.exists(): out.write_text(payload,encoding="utf-8")
  print(json.dumps({"status":"IMPORTED_OR_RESUMED","documents":len(m["documents"]),"units":len(units)})); return 0
 if errors: print(json.dumps({"status":"BLOCKED","errors":errors})); return 1
 if not args.namespace: raise ValueError("explicit --namespace required")
 selected=[]
 for d in m["documents"]:
  ns=d["id"].rsplit(":",1)[0]
  if ns!=args.namespace: continue
  if any(getattr(args,k,None) and getattr(args,k) not in d.get(("technologies" if k=="technology" else "cpcs"),[]) for k in ("technology","cpc")): continue
  if args.document_type and d.get("document_type")!=args.document_type: continue
  if args.application_id and d.get("application_id")!=args.application_id: continue
  selected.append({"document":d,"available_units":[u for u in d.get("units",[]) if u["id"] in units]})
 print(json.dumps({"results":selected,"errors":errors},indent=2)); return bool(errors)
if __name__=="__main__":
 try: sys.exit(main())
 except (KeyError,TypeError,ValueError,OSError) as e: print(json.dumps({"status":"BLOCKED","error":str(e)})); sys.exit(2)
