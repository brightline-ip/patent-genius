def _allowed_roots():
    """Directories from which file_path may be read. PG_TOOL_INPUT_ROOTS (os.pathsep-separated, absolute paths only) replaces the
    default (<install>/examples and <data dir>/inputs). Relative entries and filesystem roots are ignored so a mistyped setting cannot
    open the whole disk; roots are resolved (symlinks followed) before comparison."""
    env = os.environ.get('PG_TOOL_INPUT_ROOTS')
    roots = [Path(p) for p in env.split(os.pathsep) if p.strip()] if env else [ld.ROOT / 'examples', ld.DATA / 'inputs']
    return [r.resolve() for r in roots if r.is_absolute() and r.parent != r]


def _read_allowed_file(raw):
    """Read a .txt/.md file confined to the allowed roots. The path is resolved first (so '..' segments and symlinks are followed to
    the real target) and the real target must lie inside a resolved root; the read is bounded and re-checks the target after opening."""
    if not isinstance(raw, str) or '\0' in raw: raise ToolError('out_of_scope_path', 'file_path is not valid')
    if paths_mod.has_stream_syntax(raw): raise ToolError('out_of_scope_path', 'file_path must be a plain file path: a ":" beyond the drive letter (an NTFS alternate data stream such as file.txt:name) is never read')
    try:
        p = Path(raw).resolve()
        inside = p.suffix.lower() in ('.txt', '.md') and not paths_mod.has_stream_syntax(p) and any(p.is_relative_to(r) for r in _allowed_roots())
    except (OSError, ValueError, RuntimeError):
        inside = False
    if not inside: raise ToolError('out_of_scope_path', 'file_path must be a .txt or .md file under an allowed input root (PG_TOOL_INPUT_ROOTS)')
    try:
        with open(p, 'rb') as fh:
            if not stat.S_ISREG(os.fstat(fh.fileno()).st_mode): raise ToolError('out_of_scope_path', 'file_path must be a regular file')
            if Path(raw).resolve() != p: raise ToolError('out_of_scope_path', 'file_path changed while it was being opened')
            if not os.path.samestat(os.fstat(fh.fileno()), os.stat(p)): raise ToolError('out_of_scope_path', 'file_path changed while it was being opened')   # the opened file is the resolved path
            data = fh.read(MAX_INPUT_BYTES + 1)
    except (FileNotFoundError, IsADirectoryError, PermissionError, NotADirectoryError): raise ToolError('not_found', 'file not found', 'not_found')
    except OSError: raise ToolError('not_found', 'file could not be read', 'not_found')
    if len(data) > MAX_INPUT_BYTES: raise ToolError('too_large', f'file exceeds {MAX_INPUT_BYTES} bytes')
    return data.decode('utf-8', errors='replace')


def _source(req):
    if req.get('text') is not None:
        t = req['text']
        if len(t.encode('utf-8')) > MAX_INPUT_BYTES: raise ToolError('too_large', f'text exceeds {MAX_INPUT_BYTES} bytes')
        return t, {'kind': 'caller-text'}, {}, 'caller-supplied'
    if req.get('file_path'):
        t = _read_allowed_file(req['file_path'])
        if t.startswith('---') and '\n---\n' in t: t = t.split('\n---\n', 1)[1]
        return t, {'kind': 'caller-file'}, {}, 'caller-supplied'
    app, doc = req['application_number'], req['document_id']
    got = ld.document_text(app, doc)
    if got is None:
        known = [d['document_id'] for d in (ld.documents(app) or []) if d['code'] in ('CTNF', 'CTFR', 'CTRS', 'CTEQ', 'CTAV')]
        raise ToolError('not_found', f'document not in the local corpus; local office-action documents for this application: {", ".join(known) or "none"}', 'not_found')
    meta, t = got
    return t, {'kind': 'local-corpus', 'application_number': app, 'document_id': doc}, meta, 'public'


CANDIDATES, QUESTIONS = pt.CANDIDATES, pt.QUESTIONS   # one copy of the fixed menu and prompts, shared with the response pack


def _stats_for(statutes, ctx):
    out = []
    d = ld.oa_data()
    for dim, val in (('stratum', ctx.get('stratum')), ('cpc_group', ctx.get('cpc_group')), ('art_unit', ctx.get('art_unit'))):
        if not val: continue
        t = ld.trends(dim, groups=[val])
        for row in t['rows']:
            for s in statutes:
                if s in row['rates']:
                    out.append({'source': 'strict rule over corpus/oa-rejections/' + ','.join(d['frames']), 'table': f'Share of applications ever receiving the rejection, by {dim}',
                                'row': f'{dim}={val}', 'column': s, 'value': f"{100 * row['rates'][s]:.1f}%", 'n': row['n'], 'unit': 'applications', 'kind': 'population'})
        if not t['rows']: out.append({'source': 'strict rule (pg_tool.local_data)', 'table': f'by {dim}', 'row': f'{dim}={val}', 'column': '-', 'value': f'suppressed (fewer than {t["min_n"]} applications)', 'n': 0, 'unit': 'applications', 'kind': 'population'})
    return out


def assess(req, _loaded=None):
    text, src, meta, lane = _loaded or _source(req)
    app = req.get('application_number') or src.get('application_number')
    code = (meta.get('index_code') or meta.get('document_code')) if meta else None
    ocr = ('OCR' in (meta.get('text_fidelity') or '') or bool(meta.get('ocr_run'))) if meta else None
    parsed = oa_parse.parse(text, document_id=req.get('document_id'), application_number=app, document_code=code, mail_date=meta.get('official_date') if meta else None, ocr=ocr, now=now())
    an, ann, facts, nr = parsed['analysis'], parsed['annotations'], parsed['facts'], parsed['not_recognised']
    src.update({'chars': len(text), 'sha256': hashlib.sha256(text.encode('utf-8')).hexdigest()})
    fr = ld.frames().get(app) if app else None  # local public frame row; no provider call is ever derived from caller text
    ctx = {k: v for k, v in (req.get('context') or {}).items() if v}
    if fr:
        ctx.setdefault('stratum', fr['stratum'])
        if fr.get('art_unit'): ctx.setdefault('art_unit', fr['art_unit'])
        if fr.get('cpc'): ctx.setdefault('cpc', fr['cpc'][0])
    if ctx.get('cpc'): ctx['cpc_group'] = ctx['cpc'].replace(' ', '').split('/')[0]
    if ctx.get('stratum'): an['application']['technology'] = ctx['stratum']
    if ctx.get('art_unit'): an['application']['art_unit'] = ctx['art_unit']

    conformance = {'schema': 'schemas/office-action-analysis.schema.json', 'checked': False}
    if ANALYSIS_SCHEMA.exists():
        sch = json.loads(ANALYSIS_SCHEMA.read_text(encoding='utf-8')); errs = schema_errors(an, sch)
        conformance = {'schema': 'schemas/office-action-analysis.schema.json', 'schema_version': '1.0', 'checked': True, 'valid': not errs, 'errors': errs[:20]}

    # plan outline
    asm = an['allowable_subject_matter']['indicated']
    plan, order = [], 0

    def add(ids, title, steps, qs, kind=None):
        nonlocal order
        plan.append({'order': order, 'issue_ids': ids, 'title': title, 'template': None, 'candidate_strategies': CANDIDATES.get(kind, []), 'triage_rows': [], 'steps': steps, 'open_questions': qs}); order += 1

    add([], f"Confirm action type ({facts['finality']}; basis: {facts['finality_basis']}) and the reply period from the official record",
        ['Read the mail date and reply period on the official office action; this tool computes no deadline.'] + (['Final action: decide between an after-final response, RCE or appeal before drafting.'] if facts['finality'] == 'final' else []),
        ['Is an extension of time needed or available?'])
    if an.get('restriction'):
        add(['restriction'], 'Restriction / election requirement', ['An election is required to avoid abandonment.'], QUESTIONS['restriction'], 'restriction')
    order_rank = lambda r: (0 if r['statute'].startswith('112') or (r.get('statutory_subsection') or '').startswith('112') else 2 if r['statute'] == '101' else 3 if r['statute'] == '102' else 4 if r['statute'] == '103' else 5 if r['statute'].startswith('double') else 6)
    if asm:
        ids = [o['id'] for o in an['objections'] if o.get('allowable_if_rewritten')] or ['allowable_subject_matter']
        add(ids, f"Allowable subject matter indicated (claims {', '.join(map(str, an['allowable_subject_matter'].get('claims', []))) or 'see action'})", ['Decide whether to rewrite allowable claims, keep broader claims, or both (continuation).'], QUESTIONS['allowable'], 'objection_allowable')
    for r in sorted(an['rejections'], key=order_rank):
        s = r['statute']; fam = '112' if (s.startswith('112') or (r.get('statutory_subsection') or '').startswith('112')) else 'double_patenting' if s.startswith('double') else s
        a = ann.get(r['id'], {})
        claims = ', '.join(map(str, r['claims'])) if r['claims'] else 'claims not determined'
        steps = [f"Rejection under {r.get('statutory_subsection') or s} of claims {claims}" + (f" over {', '.join(r.get('reference_ids', []))}" if r.get('reference_ids') else '') + '.']
        if a.get('basis') == 'heading_only': steps.append('Found only by section heading: read the section to identify the claims and grounds.')
        add([r['id']], f"{s} rejection" + (f" ({a.get('ground')})" if a.get('ground') else ''), steps, QUESTIONS.get(fam, []), 'double_patenting' if fam == 'double_patenting' else 'rejection')
    for o in an['objections']:
        if o.get('allowable_if_rewritten'): continue
        add([o['id']], f"{o['kind']} objection" + (f" (claims {', '.join(map(str, o.get('claims', [])))})" if o.get('claims') else ''), ['Every objection needs a reply (correct, traverse, or request abeyance where permitted).'], QUESTIONS['objection'], 'objection')

    statutes = sorted({('112' if r['statute'].startswith('112') else 'double_patenting' if r['statute'].startswith('double') else r['statute']) for r in an['rejections'] if r['statute'] != 'other'})
    stats = _stats_for(statutes, ctx) if req.get('include_statistics', True) else []

    if req.get('include_excerpts'):
        for coll in (an['rejections'], an['objections']):
            for f in coll:
                lo = f.get('locator') or {}
                if 'char_start' in lo: ann.setdefault(f['id'], {})['excerpt'] = text[lo['char_start']:lo['char_end']][:EXCERPT_CAP]
    for x in nr['ignored_rejection_sentences']: x.pop('excerpt', None)
    untrusted.clean_analysis(an, ann, nr, parsed['header'], plan)   # strings copied from the document: control and bidi characters removed, capped

    interp = {'status': 'not_requested', 'label': 'No model interpretation; all content is deterministic.'}
    if req.get('interpretation') == 'request':
        interp = {'status': 'unavailable', 'label': 'Model interpretation is not enabled in this installation (needs a separate approval because it would send text to a model provider).'}
    data = {'source': src, 'action_facts': facts, 'context': {k: v for k, v in ctx.items() if k in ('stratum', 'cpc', 'cpc_group', 'art_unit')}, 'analysis': an, 'parser_annotations': ann,
            'schema_conformance': conformance, 'header': parsed['header'], 'plan_outline': plan, 'statistics': stats, 'not_recognised': nr,
            'parser': {'name': oa_parse.PARSER, 'version': oa_parse.VERSION, 'validation': PARSER_VALIDATION}}
