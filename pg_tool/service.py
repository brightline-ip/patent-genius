def _db_path(): return ld.DATA / 'corpus' / 'pg.db'


def _similar_query(req):
    """Everything the finder and the pack need from one request: features with provenance, the applications to leave out, the parsed
    action (if text, a file or a local document was given), and the lane. Header facts read from caller text are used here only to
    filter local results in memory: no provider or network query is made from them (local read-only database queries only) and nothing is written."""
    loaded, assessed, text, lane = None, None, None, 'public'
    if req.get('text') is not None or req.get('file_path') or (req.get('application_number') and req.get('document_id')):
        loaded = _source(req); text, lane = loaded[0], loaded[3]
        ctx = {k: v for k, v in (req.get('context') or {}).items() if k in ('cpc', 'art_unit') and v}
        st, assessed, prov, cav, warn, lane, interp = assess({'include_statistics': False, 'include_excerpts': False, 'application_number': req.get('application_number'), 'document_id': req.get('document_id'), 'context': ctx}, _loaded=loaded)
    if req.get('features') is not None: lane = 'caller-supplied'
    feat, how = {}, {}
    if assessed:
        feat, how = sim_mod.features_from_analysis(assessed['analysis'], assessed['header'], assessed['action_facts'])
        for word in ('alice', 'mayo'):
            if re.search(r'\b' + word + r'\b', text, re.I): feat[word] = True; how[word] = f'the word "{word.title()}" appears in the text'
    for k in ('cpc', 'art_unit', 'examiner'):
        v = (req.get('context') or {}).get(k)
        if v: feat[k] = sim_mod.norm_examiner(v) if k == 'examiner' else v; how[k] = 'supplied in the request context'
    if req.get('features') is not None:
        f2, h2 = sim_mod.clean_features(req['features'], how, 'supplied in the request')
        feat.update(f2); how.update(h2)
    if feat.get('art_unit') is not None and not re.fullmatch(r'\d{4}', str(feat['art_unit'])): raise ToolError('invalid_input', 'art_unit must be four digits')
    exclude, why = set(), {}
    own = req.get('application_number')
    if own: exclude.add(own); why[own] = 'application_number in the request'
    for a in req.get('exclude_applications') or []: exclude.add(a); why[a] = 'exclude_applications'
    hdr = ((assessed or {}).get('header') or {}).get('application_number') if assessed else None
    if hdr and re.fullmatch(r'\d{8}', hdr.get('value', '')): exclude.add(hdr['value']); why[hdr['value']] = 'application number read from the text (unverified); used only to leave it out of the results'
    if own and _db_path().is_file():   # an application the caller names: fill in what the database holds about it (a local read)
        try:
            rec = sim_mod.record_features(_db_path(), own)
            for k, v in rec.items():
                if v and k not in feat: feat[k] = v; how[k] = 'application record in your database'
        except sim_mod.SimilarError: pass
    if not feat: raise ToolError('invalid_input', 'no feature could be read: give the office action text, or features such as statutes or an art unit')
    return {'features': feat, 'how': how, 'exclude': sorted(exclude), 'exclude_why': why, 'assessed': assessed, 'text': text, 'lane': lane}


def _run_similar(req, q):
    try:
        w = sim_mod.effective_weights(ld.DATA, req.get('weights'))
        d = w['defaults']
        res = sim_mod.find(_db_path(), q['features'], weights=w, exclude_applications=q['exclude'], filters=req.get('filters'), require=req.get('require') or (),
                           limit=req.get('limit', d['limit']), min_score=req.get('min_score', d['min_score']), include_outcomes=req.get('include_outcomes', True),
                           min_n=req.get('min_n', d['min_n']), pool_cap=d['pool_cap'])
    except sim_mod.SimilarError as e:
        raise ToolError(e.code, str(e), 'not_found' if e.code == 'not_found' else 'error')
    res['query'] = {'features': q['features'], 'provenance': q['how'], 'excluded_applications': q['exclude_why'],
                    'note': 'Features read from text are rule-extracted and unverified. The examiner is as named on the application record now.'}
    return res


