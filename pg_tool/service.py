# ---------------- pg_search ----------------
def pg_search(req):
    src, limit = req['source'], req.get('limit', 20)
    if src != 'local-frames': raise ToolError('invalid_input', 'source must be local-frames: live provider search is planned and is not part of 0.1.0')
    fr = ld.frames(); q = (req.get('query') or '').lower(); cpc = req.get('cpc'); pat = req.get('patent_number')
    rows = []
    for a, r in fr.items():
        if req.get('application_number') and a != req['application_number']: continue
        if pat and r.get('patent_number') != pat: continue
        if req.get('stratum') and req['stratum'] not in (r.get('fields') or [r.get('stratum')]): continue
        if req.get('art_unit') and r.get('art_unit') != req['art_unit']: continue
        if req.get('filing_year') and r['filing_year'] != str(req['filing_year']): continue
        if cpc and not any(c.replace(' ', '').startswith(cpc) for c in r.get('cpc') or []): continue
        if q and q not in (r.get('applicant') or '').lower() and not any(q in c.lower() for c in r.get('cpc') or []): continue
        rows.append(r)
    rows.sort(key=lambda r: r['application_number'])
    off = int(req['cursor']) if (req.get('cursor') or '').isdigit() else 0
    page = rows[off:off + limit]; nxt = str(off + limit) if off + limit < len(rows) else None
    return ('ok' if page else 'not_found', {'source': src, 'results': page, 'total_reported': len(rows), 'next_cursor': nxt, 'complete': nxt is None},
            [{'kind': 'local', 'ref': 'corpus/frames/*.json.gz (eligible rows)'}], ['Frames cover only the filings and technology strata you built; absence here is not absence from the USPTO.', 'Live provider search is planned and not part of 0.1.0.'], [])


