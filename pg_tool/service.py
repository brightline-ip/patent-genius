def now(): return datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')


class ToolError(Exception):
    def __init__(self, code, message, status='error'): super().__init__(message); self.code, self.status = code, status


def envelope(tool, req, status, data, *, provenance=(), caveats=(), warnings=(), lane='public', live_calls=0, hub_store=False, interpretation=None, error=None):
    env = {'tool': tool, 'contract_version': CONTRACT_VERSION, 'schema_version': CONTRACT['tools'][tool]['schema_version'], 'generated_at': now(),
           'status': status, 'data': data or {}, 'provenance': list(provenance), 'caveats': list(caveats), 'warnings': list(warnings), 'disclaimer': DISCLAIMER,
           'boundary': {'lane': lane, 'classification': CALLER_CLASS if lane == 'caller-supplied' else 'public', 'matter': 'client' if lane == 'caller-supplied' else None, 'persisted_by_tool': False,
                        'hub_store': hub_store, 'model_used': False, 'live_calls': live_calls,
                        'note': 'persisted_by_tool covers this tool only; what the calling agent retains (transcripts, memory) is outside its control.'},
           'interpretation': interpretation or {'status': 'not_requested', 'label': 'No model interpretation; all content is deterministic.'}}
    for k in ('request_id', 'matter_ref'):
        if isinstance(req, dict) and isinstance(req.get(k), str): env[k] = req[k][:80]
    if error: env['error'] = error
    return env


def _validate(tool, req):
    schema = CONTRACT['$defs'][CONTRACT['tools'][tool]['input']['$ref'].split('/')[-1]]
    errs = schema_errors(req, schema, CONTRACT)
    if errs: raise ToolError('invalid_input', '; '.join(errs[:8]))


