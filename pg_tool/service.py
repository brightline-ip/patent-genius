def pg_corpus(req):
    app = req['application_number']
    docs = ld.documents(app)
    if docs is None: raise ToolError('not_found', 'no normalized documents for this application in the local corpus', 'not_found')
    codes = set(req.get('document_codes') or [])
    listing = [d for d in docs if not codes or d['code'] in codes]
    data = {'application_number': app, 'documents': listing}
    prov = [{'kind': 'local', 'ref': f'corpus/normalized/{app}/index.json'}]
    warnings = [f"{sum(1 for d in docs if not d['present'])} indexed document file(s) missing (pruned or not yet written)"] if any(not d['present'] for d in docs) else []
    if req.get('document_id'):
        got = ld.document_text(app, req['document_id'])
        if got is None: raise ToolError('not_found', 'document not found in the local corpus', 'not_found')
        meta, text = got; off = req.get('offset', 0); n = req.get('max_chars', 8000)
        data['document'] = {'document_id': req['document_id'], 'code': meta.get('document_code'), 'metadata': {k: meta.get(k) for k in ('official_date', 'source', 'source_locator', 'text_fidelity', 'derivative', 'xml_sha256', 'markup', 'ocr_run')},
                            'text': text[off:off + n], 'offset': off, 'next_offset': off + n if off + n < len(text) else None, 'total_chars': len(text)}
        prov.append({'kind': 'local', 'ref': f"corpus/normalized/{app}/{req['document_id']}.md", 'note': meta.get('derivative') or ''})
    cav = ['Normalized Markdown of USPTO public documents; not the official record. Check quotations against the file wrapper, especially OCR text.']
    return ('partial' if warnings else 'ok'), data, prov, cav, warnings


