def pg_post_grant(req):
    pat, app = req.get('patent_number'), req.get('application_number')
    fam = ld.family_index() or {'by_patent': {}, 'by_application': {}}
    if pat and not app: app = ld.patent_to_app().get(pat) or (fam['by_patent'].get(pat) or {}).get('application')
    if app and not pat: pat = (ld.frames().get(app) or {}).get('patent_number') or (fam['by_application'].get(app) or {}).get('patent')
    tr = ld.trials_index(); ap = ld.appeals_index(); cf = ld.cafc_index()
    trials = []
    if tr:
        seen = set()
        for t in (tr['by_patent'].get(pat, []) if pat else []) + (tr['by_application'].get(app, []) if app else []):
            k = (t['trial'], t['document_identifier'])
            if k not in seen: seen.add(k); trials.append(t)
    trials.sort(key=lambda t: (t['trial'] or '', t['document_date'] or ''))
    appeals = sorted(ap.get(app, []), key=lambda a: a['document_date'] or '') if (ap and app) else []
    cafc = cf.get(pat, []) if (cf and pat) else []
    pros = ld.prosecution_for(app) if app else None
    warnings, prov = [], []
    for name, ok, ref in (('ptab-trials', tr is not None, 'corpus/ptab/trials.jsonl.gz'), ('ptab-appeals', ap is not None, 'corpus/ptab/appeals.part.jsonl'), ('federal-circuit', cf is not None, 'corpus/cafc/excerpts.jsonl.gz'), ('family', bool(fam['by_patent']), 'corpus/cafc/cited-apps.jsonl')):
        if ok: prov.append({'kind': 'local', 'ref': ref})
        else: warnings.append(f'local dataset missing: {ref}')
    coverage = {'ptab_trials': 'bulk PTAB AIA trial decision documents (USPTO ODP), if you downloaded them',
                'ptab_appeals': 'ex parte appeal decision records, if you downloaded them; a download may be partial',
                'federal_circuit': 'GovInfo Federal Circuit opinions matched to cited patent numbers, if you downloaded them; opinions without a GovInfo granule are not covered',
                'family': 'continuity data only for patents cited in those opinions',
                'prosecution_rejections': f"strict-rule rejections from finished OA frames ({', '.join(ld.oa_data()['frames'])})" if app else None,
                'note': 'Absence of a record is not proof that no proceeding exists.'}
    data = {'patent_number': pat, 'application_number': app, 'ptab_trials': trials, 'ptab_appeals': appeals, 'federal_circuit': cafc,
            'family': fam['by_patent'].get(pat) or fam['by_application'].get(app), 'prosecution_rejections': sorted({x for a in pros['actions'] for x in a['rejections']}) if pros else None,
            'prosecution_actions': pros['actions'] if pros else None, 'frame_row': ld.frames().get(app) if app else None, 'coverage': coverage}
    found = trials or appeals or cafc or pros
    cav = ['Descriptive public-record lookup of the data in your data folder; not a validity, infringement or freedom-to-operate assessment.']
    return ('ok' if found and not warnings else 'partial' if found else 'not_found'), data, prov, cav, warnings


