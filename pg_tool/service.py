def call(tool, req):
    """Run one tool. Always returns an envelope; never raises; never echoes caller text in errors."""
    if tool not in TOOLS: return envelope('pg_status', {}, 'error', {}, error={'code': 'invalid_input', 'message': 'unknown tool'}) | {'tool': str(tool)[:40]}
    req = req if isinstance(req, dict) else {}
    lane = 'caller-supplied' if (req.get('text') is not None or req.get('file_path') or ((req.get('subject') or {}).get('office_action') or {}).get('text') is not None
                                 or ((req.get('subject') or {}).get('office_action') or {}).get('file_path')
                                 or (tool in ('pg_similar_office_actions', 'pg_response_pack') and req.get('features') is not None)) else 'public'
    try:
        _validate(tool, req)
        res = TOOLS[tool](req)
        status, data, prov, cav, warn = res[:5]
        kw = {'lane': lane}
        if tool == 'pg_assess_office_action': kw.update(lane=res[5], interpretation=res[6])
        if tool == 'pg_report': kw.update(lane=res[5])
        if tool in ('pg_similar_office_actions', 'pg_response_pack'): kw.update(lane=res[5])
        env = envelope(tool, req, status, data, provenance=prov, caveats=cav, warnings=warn, **kw)
        if tool in UNTRUSTED_TEXT_TOOLS and untrusted.CAVEAT not in env['caveats']: env['caveats'].append(untrusted.CAVEAT)
        return env
    except ToolError as e:
        return envelope(tool, req, e.status, {}, lane=lane, error={'code': e.code, 'message': str(e)})
    except Exception as e:  # never leak input or stack traces
        return envelope(tool, req, 'error', {}, lane=lane, error={'code': 'internal', 'message': f'internal error ({type(e).__name__})'})
