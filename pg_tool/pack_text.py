"""Every sentence in a response pack comes from this file, and every variable part of a sentence is a TYPED SLOT.

The guarantee is worded narrowly on purpose: the pack contains no tool-authored argument text. A slot accepts only a claim list,
a statute code, a normalised document number, a real date, a four-digit art unit, an eight-digit application number, a count, a
percentage, a name in USPTO form, or one of a fixed set of words. Anything else is refused (SlotError) and the caller leaves the
fact out. There is no slot for free text: a verbatim quotation can appear only in the separate, off-by-default `untrusted_quote`
field of an issue (pg_tool/pack.py), which is fenced, capped and labelled as untrusted data.

Because every string is a template filled with validated slots, `known_string(s)` can decide for any string in a pack whether it
could have come from here; tests walk a whole pack with it and fuzz every slot type with hostile strings."""
