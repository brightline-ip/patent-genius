class SlotError(ValueError):
    pass


def _claims(v):
    if not isinstance(v, (list, tuple)) or not v or len(v) > 1000 or any(isinstance(x, bool) or not isinstance(x, int) or not 1 <= x <= 1000 for x in v): raise SlotError('claims')
    xs = sorted(set(v)); out, i = [], 0
    while i < len(xs):
        j = i
        while j + 1 < len(xs) and xs[j + 1] == xs[j] + 1: j += 1
        out.append(str(xs[i]) if i == j else f'{xs[i]}-{xs[j]}'); i = j + 1
    return ', '.join(out)


def _docnums(v):
    if not isinstance(v, (list, tuple)) or not v or len(v) > 40 or any(not isinstance(x, str) or not _DOCNUM.match(x) for x in v): raise SlotError('docnums')
    return ', '.join(sorted(set(v)))


def _date(v):
    if not isinstance(v, str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', v): raise SlotError('date')
    try: datetime.date.fromisoformat(v)
    except ValueError: raise SlotError('date')
    return v


def _count(v):
    if isinstance(v, bool) or not isinstance(v, int) or not 0 <= v <= 10 ** 9: raise SlotError('count')
    return f'{v:,}' if v >= 10000 else str(v)


def _share(v):
    if isinstance(v, bool) or not isinstance(v, (int, float)) or not 0 <= v <= 1: raise SlotError('share')
    return f'{100 * v:.1f}%'


def _enum(name):
    def f(v):
        if v not in ENUMS[name]: raise SlotError(name)
        return v
    return f


def _labels(v):
    if not isinstance(v, (list, tuple)) or not v or any(x not in LABELS for x in v): raise SlotError('labels')
    return ', '.join(v)


def _plain(pattern, name, fn=lambda v: v):
    rx = re.compile(pattern)
    def f(v):
        if not isinstance(v, str) or not rx.fullmatch(v): raise SlotError(name)
        return fn(v)
    return f


def _examiner(v):
    if not isinstance(v, str) or not _NAME.match(v): raise SlotError('examiner_name')
    return v.upper()


