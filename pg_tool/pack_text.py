def slot(kind, value):
    """Validate one value as a slot of the given type and return its text; SlotError if it does not fit."""
    try: return SLOT_TYPES[kind][0](value)
    except SlotError: raise
    except (TypeError, ValueError, KeyError, AttributeError): raise SlotError(kind)   # unhashable, wrong type, anything odd: refused, never coerced


def render(template_id, **slots):
    text, spec = TEMPLATES[template_id]
    if set(slots) != set(spec): raise SlotError(f'{template_id}: expected slots {sorted(spec)}')
    return text.format(**{k: slot(spec[k], v) for k, v in slots.items()})


def try_render(template_id, **slots):
    """render(), or None when a slot value is not acceptable (the caller then leaves that fact out)."""
    try: return render(template_id, **slots)
    except SlotError: return None


def _pattern(template_id):
    text, spec = TEMPLATES[template_id]
    parts = re.split(r'\{(\w+)\}', text)
    return re.compile('^' + ''.join(re.escape(p) if i % 2 == 0 else '(?:' + SLOT_TYPES[spec[p]][1] + ')' for i, p in enumerate(parts)) + '$')


_PATTERNS = None
ATOMIC_LEAVES = ('date', 'art_unit', 'app_no', 'examiner_name', 'issue_id', 'field', 'cpc', 'version')   # values that may stand alone as a field value


def known_string(s, extra=()):
    """True when s is a rendered template, a validated slot value, the draft header, or one of `extra` (fixed strings from authorities.json etc.)."""
    global _PATTERNS
    if _PATTERNS is None: _PATTERNS = [_pattern(t) for t in TEMPLATES if t != 'authority_line']
    if s == DRAFT_HEADER or s in extra: return True
    if any(p.match(s) for p in _PATTERNS): return True
    if s in LABELS or s in STATUTES or any(s in v for v in ENUMS.values()) or _DOCNUM.match(s): return True
    return any(re.fullmatch(SLOT_TYPES[k][1], s) for k in ATOMIC_LEAVES)
